#!/usr/bin/env node
// Resolve an ENGINE film (a papercut film drawn by the huashu engine) for one language, before anything is drawn:
//   node pipeline/plan.mjs <film dir> <lang> <out dir>
// film.json gives the shots on the beat grid and each shot's cues; copy.json gives the words. The captions'
// reading time may lengthen a shot (whole beats only, so every cut stays on the grid), and a cue may be tied to a
// pop word ("word:law"), or to a line of the shot's caption ("line:2", "line:3.start") when a shot has several hits —
// a spelling only matches one language, a line is in the same place in all three. Out:
//   plan.json       the one timeline: beats, shots, cues, captions with every word's time — the caption pass,
//                   the score and the checks all read this, so they cannot disagree
//   film-plan.js    the same, as window.FILM_PLAN, for the engine's scenes
//   eras.js         the engine's era table for this language (shot durations from the plan, hard cuts). The plan
//                   loads FIRST: the kits read window.FILM_PLAN as they load, and with the plan last every cue in
//                   the picture silently fell back to its scene's default while the score hit the planned times
import fs from 'node:fs';
import path from 'node:path';
import * as CAP from './text/captions.js';

const [DIR, LANG = 'en', OUT] = process.argv.slice(2);
const film = JSON.parse(fs.readFileSync(path.join(DIR, 'film.json'), 'utf8'));
const copy = JSON.parse(fs.readFileSync(path.join(DIR, 'copy.json'), 'utf8'));
const B = 60 / film.bpm;

// the base cut: shot starts s1..sN, any marks inside a shot (in beats from its start), and the end
const beats = []; let t = 0;
film.shots.forEach((s, i) => {
  beats.push([`s${i + 1}`, t]);
  for (const [k, b] of Object.entries(s.marks || {}).sort((a, b) => a[1] - b[1])) beats.push([k, t + b * B]);
  t += s.beats * B;
});
beats.push(['end', t]);
const P = CAP.plan(copy, LANG, beats, { snap: B });

const shots = film.shots.map((s, i) => ({ id: s.id, t0: P.T[`s${i + 1}`], dur: (i + 1 < film.shots.length ? P.T[`s${i + 2}`] : P.T.end) - P.T[`s${i + 1}`] }));
const norm = (w) => w.toLowerCase().replace(/[^\p{L}\p{N}]/gu, '');
const cues = {};
film.shots.forEach((s, i) => {
  for (const [name, spec] of Object.entries(s.cues || {})) {
    let v;
    if (typeof spec === 'number') v = shots[i].t0 + spec;
    else {
      const m = /^(word|mark|line):([^+-]+)([+-][\d.]+)?$/.exec(spec); if (!m) throw new Error(`cue ${name}: ${spec}`);
      if (m[1] === 'mark') v = P.T[m[2]];
      else if (m[1] === 'line') {                                  // "line:2" = the last word of line 2 of the shot's caption, "line:3.start" its first —
        const [n, edge] = m[2].split('.'), inShot = (w) => w.t >= shots[i].t0 - 1e-6 && w.t < shots[i].t0 + shots[i].dur;   // the same place in every language,
        const cap = P.captions.find((c) => c.words.some(inShot)); const ws = cap ? cap.words.filter((w) => w.line === Number(n) - 1) : [];   // where a spelling is not
        if (!ws.length) throw new Error(`cue ${name}: no line ${n} in shot ${i + 1}`);
        v = (edge === 'start' ? ws[0] : ws[ws.length - 1]).t;
      }
      else {                                                       // the shot's own pop word, in THIS language: its position, not its spelling
        const pops = P.captions.flatMap((c) => c.words.filter((w) => w.pop && w.t >= shots[i].t0 - 1e-6 && w.t < shots[i].t0 + shots[i].dur));
        const own = P.captions.flatMap((c) => c.words).find((w) => norm(w.w) === norm(m[2]) && w.t >= shots[i].t0 - 1e-6 && w.t < shots[i].t0 + shots[i].dur);
        const w = own || (m[2] === 'pop' ? pops[0] : null) || pops[0];
        if (!w) throw new Error(`cue ${name}: no word ${m[2]} in shot ${i + 1}`);
        v = w.t;
      }
      v += m[3] ? Number(m[3]) : 0;
    }
    cues[`${s.id}.${name}`] = +v.toFixed(4);
  }
});
const plan = { film: copy.film, lang: LANG, bpm: film.bpm, fps: film.fps, T: P.T, end: P.T.end, holds: P.holds, shots, cues, captions: P.captions, ui: P.ui, keep: film.keep || [],
  quiet: (film.quiet || []).map((q) => ({ t0: cues[q.from] ?? P.T[q.from], t1: cues[q.to] ?? P.T[q.to], why: q.why })) };
fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, 'plan.json'), JSON.stringify(plan, null, 1));
fs.writeFileSync(path.join(OUT, 'film-plan.js'), `// generated by pipeline/plan.mjs for ${copy.film} (${LANG}): do not edit\nwindow.FILM_PLAN = ${JSON.stringify(plan)};\n`);
const eras = `// generated by pipeline/plan.mjs for ${copy.film} (${LANG}): do not edit — shot lengths come from the copy\nwindow.FILM_SIZE = [1080, 1920];\nwindow.BPM = ${film.bpm};\nwindow.PUNCH = 0;\n` +
  `window.SCENE_LIBS = ${JSON.stringify([`scenes/${film.engine}_plan.js`, ...film.libs])};\nwindow.ERAS = [\n` + shots.map((s) => `  { id: '${s.id}', dur: ${s.dur.toFixed(6)} },`).join('\n') + '\n];\n';
fs.writeFileSync(path.join(OUT, 'eras.js'), eras);
console.log(`${copy.film} ${LANG}: ${plan.end.toFixed(2)} s, ${shots.length} shots, holds ${JSON.stringify(P.holds)}`);
