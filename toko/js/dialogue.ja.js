// else: plain form (だ・である, never です・ます), no softeners, no ね, and
// sentences short enough to stop dead. Where English drops articles for
// bluntness, this drops particles and subjects.
//
// LINE LENGTH IS NOT THE SAME PROBLEM. The panel wraps at about forty Latin
// characters; Japanese glyphs are full-width, so a line here is kept to about
// twenty. A line translated at English length wraps mid-word and the typing
// animation stutters over the break.
//
// お前 throughout is deliberate and consistent: it is the blunt, familiar
// second person, which is the closest Japanese gets to Toko's English. It is
// also rough enough to be a choice somebody should sign off on.
//
